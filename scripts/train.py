#!/usr/bin/env python3
"""Train one joint RAICL LoRA fold using packed 4-bit weights and decision-only loss."""
import argparse
import os
import sys
from pathlib import Path

os.environ.setdefault("OMP_NUM_THREADS", "4")
os.environ.setdefault("MKL_NUM_THREADS", "4")
os.environ.setdefault("OPENBLAS_NUM_THREADS", "4")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config", type=Path, help="YAML generated by raicl-prepare --training")
    parser.add_argument("--resume-from-checkpoint", type=Path)
    args = parser.parse_args()
    import yaml
    config = yaml.safe_load(args.config.read_text())
    if config.get("per_device_train_batch_size") != 1 or config.get("gradient_accumulation_steps") != 16:
        raise ValueError("The released loss optimization and protocol require batch 1 and accumulation 16")
    if config.get("do_eval") or config.get("eval_dataset"):
        raise ValueError("Do not select a checkpoint using held-out patient labels")
    if args.resume_from_checkpoint:
        if not args.resume_from_checkpoint.is_dir():
            raise FileNotFoundError("Resume checkpoint is absent")
        config["resume_from_checkpoint"] = str(args.resume_from_checkpoint.resolve())
    elif Path(config["output_dir"]).exists() and any(Path(config["output_dir"]).iterdir()):
        raise FileExistsError("Training output is not empty; resume explicitly rather than overwrite")
    import torch
    if not torch.cuda.is_available():
        raise RuntimeError("QLoRA training requires a supported CUDA GPU")
    from transformers import BitsAndBytesConfig
    original = BitsAndBytesConfig.__init__
    def uint8_storage(self, **kwargs):
        if kwargs.get("load_in_4bit"):
            kwargs["bnb_4bit_quant_storage"] = torch.uint8
        original(self, **kwargs)
    BitsAndBytesConfig.__init__ = uint8_storage
    from raicl.models import answer_only_logits
    answer_only_logits.install()
    from llamafactory.train.tuner import run_exp
    run_exp(config)


if __name__ == "__main__":
    main()
